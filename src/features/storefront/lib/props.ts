/** a row of books standing up along a shelf */
const bookrow = (
  x: number,
  y: number,
  z: number,
  n: number,
  seed = 0,
  tall = 190,
) =>
  Array.from({ length: n }, (_, i) =>
    book(
      x + i * 44,
      y,
      z,
      tall + ((i * 37 + seed * 13) % 80),
      [ink, orange, cream, textile2, green, textile][(i + seed) % 6] ?? ink,
      36,
    ),
  );

