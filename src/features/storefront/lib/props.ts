/**
 * What a piece holds once it is in use. Small stand-ins, drawn with the same
 * light as the furniture: a coat on the hook, keys in the tray, books on both
 * sides. Coordinates are local to the piece (mm): x across, y from front (0)
 * to back, z up. They appear after the piece is placed, in order.
 */
export type PropSpec = {
  name: string;
  geo: "box" | "cylinder" | "sphere";
  x: number;
  y: number;
  z: number;
  w: number;
  d: number;
  h: number;
  color: string;
};

const coat = (x: number, z: number, color: string): PropSpec => ({
  name: "coat",
  geo: "box",
  x,
  y: 180,
  z: z - 640,
  w: 210,
  d: 110,
  h: 640,
  color,
});
const book = (
  x: number,
  y: number,
  z: number,
  h: number,
  color: string,
  w = 34,
): PropSpec => ({ name: "book", geo: "box", x, y, z, w, d: 190, h, color });
const shoe = (x: number, y: number, z: number, color: string): PropSpec => ({
  name: "shoe",
  geo: "box",
  x,
  y,
  z,
  w: 95,
  d: 250,
  h: 70,
  color,
});

