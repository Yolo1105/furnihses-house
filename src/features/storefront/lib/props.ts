/* The rest of the vocabulary. Two designs may share a frame — the panel system
   is built on exactly that — so what tells them apart is what they are
   holding. These are the things, written once and stood in different places. */

const jar = (x: number, y: number, z: number, h: number, color: string) =>
  ({
    name: "jar",
    geo: "cylinder",
    x,
    y,
    z,
    w: 80,
    d: 80,
    h,
    color,
  }) satisfies PropSpec;
const bottle = (x: number, y: number, z: number, h: number, color: string) =>
  ({
    name: "bottle",
    geo: "cylinder",
    x,
    y,
    z,
    w: 70,
    d: 70,
    h,
    color,
  }) satisfies PropSpec;
const crate = (
  x: number,
  y: number,
  z: number,
  w: number,
  h: number,
  color: string,
  name = "box",
  d = 300,
) => ({ name, geo: "box", x, y, z, w, d, h, color }) satisfies PropSpec;
/** a stack of folded cloth: laundry, towels, a child's jumpers */
const folded = (x: number, y: number, z: number, n: number, color: string) =>
  Array.from({ length: n }, (_, i) =>
    crate(x, y, z + i * 46, 250, 42, color, "folded", 280),
  );
const basket = (x: number, y: number, z: number, w: number, h: number) =>
  ({
    name: "basket",
    geo: "box",
    x,
    y,
    z,
    w,
    d: 300,
    h,
    color: "#c9b59b",
  }) satisfies PropSpec;
const ball = (x: number, y: number, z: number, d: number, color: string) =>
  ({
    name: "ball",
    geo: "sphere",
    x,
    y,
    z,
    w: d,
    d,
    h: d,
    color,
  }) satisfies PropSpec;
/** a lamp in three pieces: the tall one for a bedside, a short one for a child */
